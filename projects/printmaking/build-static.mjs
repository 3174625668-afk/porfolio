// Render the confirmed cluster layout into HTML so the public preview has no
// dependency on cached CSS/JS modules. Original image files are referenced unchanged.
import { readFile, writeFile } from 'node:fs/promises';
import { artworkRecords, galleryGroups, series } from './gallery-data.js';

const escape = value => String(value).replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[char]));
const artworks = new Map(artworkRecords.map(work => [work.id, work]));
const captionsJS = await readFile(new URL('captions.js', import.meta.url), 'utf8');
const css = await readFile(new URL('gallery.css', import.meta.url), 'utf8');
let imageIndex = 0;
const groups = galleryGroups.map(group => {
  const columns = group.artworkIds.map(id => {
    const work = artworks.get(id);
    return `${work.pixelWidth / work.pixelHeight}fr`;
  }).join(' ');
  const works = group.artworkIds.map(id => {
    const work = artworks.get(id);
    const shared = series[work.seriesId];
    const chinese = work.titleZh;
    const english = work.title || shared?.name;
    const title = chinese || english;
    const caption = work.seriesId === 'apple' ? '' : `<figcaption class="artwork-caption" id="caption-${work.id}"><span class="caption-title"${chinese ? ' lang="zh"' : ''}>${escape(title)}</span>${chinese && english && chinese !== english ? `<span class="caption-english">${escape(english)}</span>` : ''}<span class="caption-details">${escape(work.medium)} · ${escape(work.year)}</span></figcaption>`;
    const interaction = work.seriesId === 'apple'
      ? ' aria-describedby="apple-series-info"'
      : ` tabindex="0" role="button" aria-label="${escape([chinese, english].filter(Boolean).join(' / '))}" aria-expanded="false" aria-controls="caption-${work.id}"`;
    return `      <figure class="artwork" data-artwork-id="${escape(work.id)}"${interaction}><img src="${escape(work.image)}" alt="${escape(title)}" width="${work.pixelWidth}" height="${work.pixelHeight}" loading="${imageIndex++ === 0 ? 'eager' : 'lazy'}" decoding="async">${caption}</figure>`;
  });
  const marks = group.decorations.map(mark => `      <span class="cluster-decoration ${mark.type}" aria-hidden="true" style="left:${mark.x}%;width:${mark.size}px;${mark.type === 'star' ? `height:${mark.size}px;` : ''}"></span>`);
  const seriesInfo = group.layout === 'apple-quartet'
    ? `<div class="series-info" id="apple-series-info" data-apple-label="centered-caption"><span class="caption-title">${escape(series.apple.name)}</span><span class="caption-details">${escape(series.apple.medium)} · ${escape(series.apple.year)}</span></div>`
    : '';
  return `    <div class="gallery-cluster layout-${group.layout} align-${group.align}" data-layout-group="${group.id}" style="--cluster-width:${group.maxWidth}px;--ratio-columns:${columns}">\n${[...works, ...marks, seriesInfo].filter(Boolean).join('\n')}\n    </div>`;
}).join('\n');
const html = `<!doctype html>
<!-- Generated by build-static.mjs from gallery-data.js and gallery.css. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Printmaking — selected works by LINJUN YE.">
  <meta name="portfolio-layout" content="printmaking-curated-clusters-v2">
  <title>Printmaking — LINJUN YE</title>
  <style>
${css}  </style>
</head>
<body>
  <main>
    <a class="back-home" href="../../">BACK TO HOME</a>
    <header class="gallery-header">
      <h1>Printmaking</h1>
      <span class="star title-star-top" aria-hidden="true"></span>
      <span class="star title-star-low" aria-hidden="true"></span>
      <span class="line title-line-left" aria-hidden="true"></span>
      <span class="line title-line-right" aria-hidden="true"></span>
    </header>
    <section id="gallery" aria-label="Printmaking artworks">
${groups}
    </section>
  </main>
  <script>
${captionsJS}  </script>
</body>
</html>
`;
await writeFile(new URL('index.html', import.meta.url), html);
await writeFile(new URL('clusters-v2.html', import.meta.url), html);
console.log(`Rendered ${imageIndex} artworks in ${galleryGroups.length} groups into both static pages.`);
