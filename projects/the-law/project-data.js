// Missing files never shift the pairing: an incomplete spread stays hidden.
export function availableInteriorUnits(pages = interiorPages) {
  return interiorUnits.filter(unit => unit.pages.every(id => pages[id])).map(unit => ({
    ...unit, images: unit.pages.map(id => ({ ...pages[id], page: id })),
  }));
}
